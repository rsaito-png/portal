### **（契約の目的）第１条**

この契約は、利用児童がその有する能力及び適性に応じ、自立した日常生活又は社会生活を営むことができるよう、事業者が利用児童に対して児童福祉法に基づく指定児童発達支援および放課後等デイサービスの事業を提供することを目的とします。

### **（契約期間）第２条**

１　この契約は、{契約開始}から{契約終了}までとします。
２　前項の契約期間満了の日に引き続き、利用児童に係る保護者の障害児通所給付費の支給決定がされたとき、その決定された期間について本契約は更新するものとします。また、それ以降の契約期間満了に伴う更新についても同様とします。ただし、契約期間満了の３０日前までに保護者から本契約を更新しない旨の申し入れがあった場合、または第１５条により本契約が解除された場合は、本契約は終了するものとします。

### **（個別支援計画）第３条**

１　児童発達支援管理責任者は、利用児童の置かれている環境及び日常生活全般の状況等を通じて保護者及び利用児童が希望する生活や課題を明らかにし、適切な支援内容の把握に基づく到達目標を設定し、サービス担当者会議を経て個別支援計画を作成します。
２　個別支援計画の内容について保護者及び利用児童に対し説明し、文書により同意を求めます。
３　個別支援計画作成後、６ヶ月に１回以上定期的に個別支援計画実施状況の把握を行い、必要に応じて個別支援計画の変更を行います。変更については保護者及び利用児童に説明をし、文書により同意を求めます。

### **（サービス内容）第４条**

１　事業者は、個別支援計画に基づいて、「重要事項説明書」に記載されているサービス内容を提供します。
２　サービスの提供は、事業所の児童指導員又は保育士等の従業者が当たります。なお、事業所は、同一敷地内の生活介護事業所「茶夢」と共生型サービス事業所として一体的に運営しています。
３　サービスの提供に当たっては利用児童の心身の状況に応じ自立の支援と日常生活の充実に資するよう、適切な技術を持って行います。
４　利用児童の意思と人格を尊重し、常に利用児童の立場に立って、サービスを提供します。

### **（利用料金）第５条**

１　事業者が利用児童に対して、障害児通所給付費対象サービスを提供した際は、サービス利用料金（こども家庭庁長官の定める基準により算出した額）のうち９割が障害児通所給付費の給付対象となります。事業者が障害児通所給付費等の給付を市町村から直接受け取る（代理受領といいます）場合、利用者負担分としてサービス利用料金全体の１割の額にあたる通所利用者負担額をお支払いいただきます。なお、利用者負担額の軽減等が適用される場合は、この限りではありません。
２　代理受領を行わない場合は、保護者から指定通所支援費用基準額の支払いを受けます。
３　事業者は、食費（１食３００円）その他障害児通所給付費対象外の費用で、重要事項説明書に定めるものについて料金を請求します。
４　事業者は、サービス利用に当たって、あらかじめ保護者に対しサービスの内容及び料金について説明を行い、保護者の同意を得ます。また、支払いを受けたときは領収証を交付します。

### **（利用料の支払い方法）第６条**

１　保護者は前条に定める利用料金を月ごとに支払います。
２　事業所は、当月の利用料金合計額の請求書を翌月１５日までに送付します。
３　保護者は、当月の利用料金の合計金額を、翌月末日までに支払います。

### **（説明義務）第７条**

事業者は、契約に基づく内容について、保護者及び利用児童の質問等に対して適切に説明します。

### **（相談及び援助）第８条**

事業者は保護者及び利用児童が希望する生活や利用者の心身の状況等を把握し、適切な相談、助言、援助を行います。

### **（安全配慮義務）第９条**

事業者は、サービスの提供にあたって、利用児童の生命、身体の安全確保に配慮するとともに、非常災害、感染症対策及び衛生管理等に必要な具体的な計画（業務継続計画を含む。）、連絡体制を講じています。

