// 受給者証の入力の一覧だけ、説明を ▽ で畳む。node tools/leo_jf_fold_test.js
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const src = read('leo_jukyusha.js');
const idx = read('index.html');
const list = src.slice(src.indexOf('LEO_VIEWS.jukyusha = async function'), src.indexOf('window.jfOpen'));
const review = src.slice(src.indexOf('async function jfReview'));
assert.ok(list.includes("leoFoldBtn('leo_jf_intro_open', 'jf_intro', '受給者証の入力（保護者から）')"));
assert.ok(list.includes("leoFoldBtn('leo_jf_link_note_open', 'jf_link_note', '1. 保護者にリンクを送る')"));
assert.ok(list.includes('leoFoldBtn(\'leo_jf_subs_open\', \'jf_subs\''));
assert.ok(list.includes('id="jf_intro"') && list.includes('id="jf_link_note"') && list.includes('id="jf_subs"'));
assert.ok(list.includes('leoFoldOpen(\'leo_jf_intro_open\')'));
assert.ok(list.indexOf('id="jf_link_note"') < list.indexOf('id="jf_child"'), '説明のあとに児童の選択');
assert.ok(list.indexOf('id="jf_child"') < list.indexOf('id="jf_prefill"') && list.indexOf('id="jf_prefill"') < list.indexOf('onclick="jfLink()"'));
assert.ok(list.indexOf('id="jf_link_note"') < list.indexOf('開いた人に、お子さんの前回の内容'));
assert.ok(list.indexOf('</div>', list.indexOf('id="jf_link_note"')) < list.indexOf('id="jf_child"') || list.includes('id="jf_child"'));
const linkNote = list.slice(list.indexOf('id="jf_link_note"'), list.indexOf('id="jf_child"'));
assert.ok(linkNote.includes('公式LINEの1対1') && linkNote.includes('30日有効') && linkNote.includes('前回の内容'));
assert.ok(!linkNote.includes('id="jf_prefill"') && !linkNote.includes('jfLink()'));
const subsFold = list.slice(list.indexOf('id="jf_subs"'), list.lastIndexOf('</div>'));
assert.ok(subsFold.includes('jf-tbl') && subsFold.includes('まだ届いていません') && subsFold.includes('一覧を読み込めませんでした'));
assert.ok(list.includes('確認待ち') && list.indexOf('確認待ち') < list.indexOf('id="jf_subs"'), '件数は見出しに残す');
assert.ok(!review.includes('leo_jf_intro_open') && !review.includes('leoFoldBtn'), '確認画面は畳まない');
assert.ok(src.includes('button:not(.nk-fold)'));
assert.ok(idx.includes('#jf_intro[hidden],#jf_link_note[hidden],#jf_subs[hidden]'));
assert.ok(idx.includes('leo_jukyusha.js?v=20261105fold'));
assert.ok(read('leo.js').includes('function leoFoldBtn'));
console.log('leo_jf_fold_test ok');
