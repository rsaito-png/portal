#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const vm = require('vm');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'leo_contract.js'), 'utf8');
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const box = { esc, LC: { link: null }, location: { origin: 'https://example.test', pathname: '/portal/' } };
box.window = box;
vm.runInNewContext(src, box);
assert.strictEqual(box.lcWareki('2026-11-12'), '令和8年11月12日');
assert.strictEqual(box.lcWareki(null), '　　年　　月　　日');
const filled = box.lcFill('保護者（氏名：{保護者}）児童（氏名：{児童}）開始{契約開始}', { guardian: '山田花子', child: '山田太郎', contract_start: '2026-11-12' });
assert.ok(filled.includes('山田花子') && filled.includes('山田太郎') && filled.includes('令和8年11月12日'));
const html = box.lcRender('# **題**\n\n本文です。\n\n| 名称 | 値 |\n| :---- | :---- |\n| レオ | テスト |\n');
assert.ok(html.includes('<h1>') && html.includes('<b>題</b>'), '見出し');
assert.ok(html.includes('<table class="lc-doc">') && html.includes('<th>') && html.includes('レオ'), '表');
assert.ok(html.includes('本文です。'), '本文を残す');
const evil = box.lcRender('<img src=x onerror=alert(1)> **太字**');
assert.ok(evil.includes('&lt;img') && !evil.includes('<img src'), 'HTMLを逃す');
assert.ok(evil.includes('<b>太字</b>'));
const cfgWin = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'config.js'), 'utf8'), { window: cfgWin });
const leo = cfgWin.PORTAL_CONFIG.offices.find(o => o.id === 'leo');
const tile = leo.tiles.find(t => t[2] === '#leo/contract');
assert.ok(tile, 'タイルがある');
assert.strictEqual(tile[1], '利用契約書・重要事項説明書');
assert.strictEqual(tile[6], '児発管');
assert.ok(leo.groups[1][2].includes('利用契約書・重要事項説明書'));

const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.ok(index.includes('leo_contract.js'));
assert.ok(index.includes("sub === 'contract'") && index.includes('renderLeoContract'));
const sign = fs.readFileSync(path.join(root, 'leo_contract_sign.html'), 'utf8');
assert.ok(sign.includes("rpc('leo_doc_get'") && sign.includes("rpc('leo_doc_submit'"));
assert.ok(sign.includes('保護者が署名する'));
assert.ok(!sign.includes('supabaseKey') || sign.includes('C.supabaseKey'), '鍵を直書きしない');
const sql = fs.readFileSync(path.join(root, 'supabase/leo_contract.sql'), 'utf8');
assert.ok(sql.includes("can_manage_for('レオ')"));
assert.ok(sql.includes("revoke all on public.%I from anon"));
assert.ok(sql.includes('grant execute on function public.leo_doc_get to anon, authenticated'));
assert.ok(!sql.includes('kin_doc_') && !sql.includes('sui_doc_'), '既存の契約RPCを触らない');
const body = fs.readFileSync(path.join(root, 'supabase/leo_contract_body.sql'), 'utf8');
assert.ok(body.includes('2450201047') || body.includes('２４５０２０１０４７'));
assert.ok(body.includes('{保護者}') && body.includes('{児童}'));
console.log('ok');
